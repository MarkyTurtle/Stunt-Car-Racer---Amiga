"""Generate a source from its config, assemble it with vasm and check it against the original.

  python3 original/tools/disasm/make.py [--write] [game] [boot] [loader] [loader4000]   (default: all)

Without --write it writes what the configs give to tools/disasm/regen/ (not kept in git) and
checks that against the original binaries: once the sources in original/ are edited by hand they
are the source, and this never writes over them. --write puts the generated sources (and
scr_hw.i, scr_equates.i) in original/ - for the first generation only.

(Adapted from the New Zealand Story repository's tools/disasm/make.py; core.py is shared.)
"""
import hashlib, importlib, os, shutil, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))          # original/
OUT = os.path.join(HERE, 'regen')
sys.path.insert(0, HERE)
import core

VASM = os.environ.get('VASM', 'vasmm68k_mot')
PROGRAMS = {            # config module, source written, original binary (file, start, length)
    'game': ('game_cfg', 'scr_game.s', ('disk/files/t010-083_game.bin', 0, None)),
    'boot': ('boot_cfg', 'scr_boot.s', ('disk/files/t000_bootblock.bin', 0, None)),
    'loader': ('loader_cfg', 'scr_loader.s', ('disk/files/t002-008_loader_packed.bin', 0, None)),
    'loader4000': ('loader4000_cfg', 'scr_loader4000.s', ('bin/loader_4000.bin', 0, None)),
}


def assemble(src, out, cwd):
    r = subprocess.run([VASM, '-Fbin', '-m68000', '-no-opt', '-quiet', '-o', out, src],
                       capture_output=True, text=True, cwd=cwd)
    if r.returncode:
        print(r.stdout + r.stderr)
        raise SystemExit(f'{src}: assembly failed')


def write_hw(out):
    """scr_hw.i: custom chip registers (offsets from CUSTOM), the CIAs, the exception vectors."""
    from hw import CUSTOM, CIAA, CIAB
    L = ['; Amiga hardware: custom chip registers (offsets from CUSTOM), CIA registers, exception vectors',
         '; Generated by tools/disasm/make.py (tools/disasm/hw.py).', '',
         'CUSTOM\t\tequ\t$DFF000\t\t; custom chip base', '']
    L += [f'{n:<12}\tequ\t${o:03X}' for o, n in sorted(CUSTOM.items())]
    L += ['', '; CIA-A (registers at $BFE001, odd addresses)']
    L += [f'{n:<12}\tequ\t${0xBFE000 + o:06X}' for o, n in sorted(CIAA.items())]
    L += ['', '; CIA-B (registers at $BFD000, even addresses)']
    L += [f'{n:<12}\tequ\t${0xBFD000 + o:06X}' for o, n in sorted(CIAB.items())]
    L += ['', '; 68000 exception vectors']
    L += [f'V_{n:<16}\tequ\t${a:02X}' for a, n in sorted(core.VECTOR_NAMES.items())]
    open(os.path.join(out, 'scr_hw.i'), 'w').write('\n'.join(L) + '\n')


def main():
    args = sys.argv[1:]
    write = '--write' in args
    names = [a for a in args if a != '--write'] or list(PROGRAMS)
    os.makedirs(OUT, exist_ok=True)
    os.environ['PATH'] = os.path.dirname(VASM) + os.pathsep + os.environ['PATH'] if os.sep in VASM else os.environ['PATH']
    write_hw(OUT)
    ok = True
    for n in names:
        mod, src, (orig, start, length) = PROGRAMS[n]
        print(f'{n}: tools/disasm/regen/{src}')
        cfg = importlib.import_module(mod)
        core.build(cfg, os.path.join(OUT, src))
        out = os.path.join(HERE, f'_{n}.bin')
        assemble(src, out, OUT)
        got = open(out, 'rb').read()
        want = open(os.path.join(ROOT, orig), 'rb').read()[start:None if length is None else start + length]
        os.remove(out)
        if got == want:
            print(f'  reassembles byte-identical to {orig} (sha1 {hashlib.sha1(got).hexdigest()})')
            if write:
                for f in [src, 'scr_hw.i'] + ([cfg.EQUATES_FILE] if getattr(cfg, 'EQUATES_FILE', None) else []):
                    shutil.copy(os.path.join(OUT, f), os.path.join(ROOT, f))
                print(f'  written to original/{src}')
        else:
            ok = False
            d = next((i for i in range(min(len(got), len(want))) if got[i] != want[i]), min(len(got), len(want)))
            print(f'  MISMATCH with {orig}: sizes {len(got)}/{len(want)}, first difference at file offset ${d:X}')
    sys.exit(0 if ok else 1)


if __name__ == '__main__':
    main()
